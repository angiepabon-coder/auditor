const assert = require('node:assert/strict');
const esbuild = require('esbuild');
const output = esbuild.buildSync({entryPoints:['src/components/indicators/indicatorRules.ts'],bundle:true,write:false,platform:'node',format:'cjs'});
const moduleObj = {exports:{}}; new Function('module','exports',output.outputFiles[0].text)(moduleObj,moduleObj.exports);
const {evaluateIndicator,meetsTarget} = moduleObj.exports;
const {reportingDeadline} = moduleObj.exports;
assert.equal(reportingDeadline('2026-01-31',5),'2026-02-05');
assert.equal(reportingDeadline('2026-03-31',5),'2026-04-05');
assert.equal(reportingDeadline('2026-12-31',5),'2027-01-05');
assert.equal(reportingDeadline('2028-02-29',5),'2028-03-05');
const base = {id:'test',centerId:'ce-1',name:'Test',frequency:'Mensual',firstMonth:'2026-07',deadlineDays:15,operator:'>=',target:99,unit:'%',responsible:'Test',email:'',source:'https://example.com',verifiedOn:'2026-10-23'};
assert.equal(evaluateIndicator(base,[],'2026-10-23').length,3);
assert.equal(evaluateIndicator({...base,deadlineDays:5},[],'2026-08-05',['2026-07'])[0].timing,'Pendiente en plazo');
assert.equal(evaluateIndicator({...base,deadlineDays:5},[],'2026-08-06',['2026-07'])[0].timing,'Sin diligenciar · vencido');
assert.equal(evaluateIndicator(base,[],'2026-10-23')[0].timing,'Diligenciamiento sin verificar');
assert.equal(evaluateIndicator(base,[],'2026-08-15',['2026-07'])[0].timing,'Pendiente en plazo');
assert.equal(evaluateIndicator(base,[],'2026-08-16',['2026-07'])[0].timing,'Sin diligenciar · vencido');
assert.equal(evaluateIndicator({...base,deadlineDays:null},[],'2026-10-23',['2026-07'])[0].timing,'Plazo sin verificar');
const m = {id:'m',indicatorId:'test',period:'2026-07',reportedOn:'2026-08-15',value:0,source:'https://example.com'};
assert.equal(evaluateIndicator(base,[m],'2026-10-23')[0].goal,'Incumple');
assert.equal(evaluateIndicator(base,[m],'2026-10-23')[0].timing,'En plazo');
assert.equal(evaluateIndicator(base,[{...m,reportedOn:'2026-08-16'}],'2026-10-23')[0].timing,'Diligenciado tarde');
assert.equal(evaluateIndicator({...base,frequency:'Trimestral'},[],'2026-10-23').length,1);
assert.equal(evaluateIndicator({...base,frequency:'Trimestral'},[],'2026-10-23')[0].due,'2026-10-15');
assert.equal(meetsTarget(99,base),true);
assert.equal(meetsTarget(0,{...base,operator:'<=',target:0}),true);
assert.equal(meetsTarget(3,{...base,operator:'Entre',target:2,upper:4}),true);
assert.equal(meetsTarget(5,{...base,operator:'Entre',target:2,upper:4}),false);
assert.equal(evaluateIndicator({...base,frequency:'Semestral',firstMonth:'2026-01'},[],'2026-10-23').length,1);
assert.equal(evaluateIndicator({...base,frequency:'Anual',firstMonth:'2026-01'},[],'2026-10-23').length,0);
assert.equal(evaluateIndicator({...base,frequency:'Anual',firstMonth:'2025-01'},[],'2026-10-23')[0].period,'2025');
